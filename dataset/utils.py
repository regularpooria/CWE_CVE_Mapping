removed_words = []


def remove_capital_words(text):

    def strip_sentence(sentence):
        first = FIRST_WORD_RE.match(sentence)
        first_end = first.end() if first else 0

        def replace(m):
            word = m.group()
            if m.start() < first_end or word in WHITELIST:
                return word
            removed_words.append((word, sentence.strip()))
            return ""

        return CAPITAL_WORD_RE.sub(replace, sentence)

    parts = SENTENCE_SPLIT_RE.split(text)
    result = "".join(
        strip_sentence(p) if i % 2 == 0 else p for i, p in enumerate(parts)
    )

    result = VERSION_RE.sub("", result)
    result = MULTI_SPACE_RE.sub(" ", result)
    result = SPACE_BEFORE_PUNCT_RE.sub(r"\1", result)
    result = result.strip()

    return result


PAREN_RE = re.compile(r"\([^)]*\)")


def remove_parentheses(description):
    return PAREN_RE.sub("", description)
